filtro_colunas = ['CIDADE','BAIRRO','LOGRADOURO','NUMERO_LOGRADOURO','NUM_BO','DATA_OCORRENCIA_BO','HORA_OCORRENCIA','DESCR_OCORRENCIA_VEICULO','DESCR_TIPO_VEICULO', 'DESCR_MARCA_VEICULO','ANO_MODELO','PLACA_VEICULO','DESC_COR_VEICULO']

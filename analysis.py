df33m_mesc_f = df33m_f.merge(df_loc[['CIDADE','BAIRRO','PLACA_VEICULO','LOGRADOURO','NUMERO_LOGRADOURO']], on='PLACA_VEICULO',  suffixes=('_robfur','_loc') )

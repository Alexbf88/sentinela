df33m_rf = df33m.query('["Furtado","Roubado"] in DESCR_OCORRENCIA_VEICULO')
df_loc = df_sp.query('"Localizado / Entregue" in DESCR_OCORRENCIA_VEICULO')

"""# Mesclando as bases de dados de furto e roubo com localização"""

#merging the robbed and stolen dataframes with the localized, using plate as reference


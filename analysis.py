#applying filters and creating the DataFrame containing all the cities within 33ºBPM/M
df33m = df_sp.query('@filtro_cidades in CIDADE').copy()
#removing every row where the vehicle plate is null, since without the plate, there will be many issues when merging
df33m.dropna(subset=['PLACA_VEICULO'], inplace=True)
df33m = df33m[filtro_colunas]
#creating subsets
df33m_r = df33m.query('"Roubado" in DESCR_OCORRENCIA_VEICULO')
